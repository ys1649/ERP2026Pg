CREATE VIEW VIEW_ERMODAL AS
SELECT Obj_Tbl.Name AS TableName,Obj_Tbl.CODE AS TableCode
, Obj_Col.NAME AS FieldName, Obj_Col.CODE AS FieldCode
, [MPDCOLN].[DTTP] AS DataType
, [MPDCOLN].[PRIM] AS PK, [MPDCOLN].[FORN] AS FK, [MPDCOLN].[MAND] AS M
, ObjFK_Tbl.CODE AS FK_Table, FKColunm.CODE AS FK_Field
, TXT_TBLDesc.TDAT AS TblDescription
, TXT_TblAnno.TDAT AS TblAnnotation
, TXT_ColDesc.TDAT AS ColDescription
, TXT_ColAnno.TDAT AS ColAnnotation
, [MPDTABL].[LABL] AS TblLabel
,[SUBM].[NAME] AS SubModal
,[MPDCOLN].[TABL], [MPDCOLN].[COLN]

FROM ((((((((((((MPDCOLN 
INNER JOIN OBJT AS Obj_Col ON [MPDCOLN].[COLN]=Obj_Col.OBJT) 
INNER JOIN OBJT AS Obj_Tbl ON [MPDCOLN].[TABL]=Obj_Tbl.OBJT) 
LEFT JOIN MPDCREF ON [MPDCOLN].[COLN]=[MPDCREF].[TRGT]) 
LEFT JOIN OBJT AS FKColunm ON [MPDCREF].[SRCE]=FKColunm.OBJT) 
LEFT JOIN MPDCOLN AS MPDCOLN_1 ON FKColunm.OBJT=MPDCOLN_1.COLN) 
LEFT JOIN OBJT AS ObjFK_Tbl ON MPDCOLN_1.TABL=ObjFK_Tbl.OBJT) 
INNER JOIN MODL ON Obj_Tbl.MODL=[MODL].[MODL]) 
LEFT JOIN VIEW_TXTS AS TXT_TBLDesc ON Obj_Tbl.DSCR=TXT_TBLDesc.BLBJ) 
LEFT JOIN VIEW_TXTS AS TXT_TblAnno ON Obj_Tbl.ANNT=TXT_TblAnno.BLBJ) 
LEFT JOIN VIEW_TXTS AS TXT_ColDesc ON Obj_Col.DSCR=TXT_ColDesc.BLBJ) 
LEFT JOIN VIEW_TXTS AS TXT_ColAnno ON Obj_Col.ANNT=TXT_ColAnno.BLBJ) 
INNER JOIN MPDTABL ON [MPDCOLN].[TABL]=[MPDTABL].[TABL]) 
LEFT JOIN (SUBO 
	LEFT JOIN SUBM ON [SUBO].[SUBM]=[SUBM].[SUBM]) ON [MPDCOLN].[TABL]=[SUBO].[OBJT]
--ORDER BY [SUBM].[NAME], Obj_Tbl.CODE, [MPDCOLN].[COLN]
GO

